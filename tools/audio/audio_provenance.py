"""Match every shipped audio file to its source pack by exact content hash.

Writes docs/AUDIO_PROVENANCE.md. Files that match no pack are listed as
"unknown"; this does not claim a license for them, it reports evidence only.

    python tools/audio/audio_provenance.py
"""
import hashlib
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GAMEDEV = Path(r"C:\Users\rober\OneDrive\Desktop\GameDev")
LICENSES = {
    "Fantasy Music Pack Vol. 7": "Ovani Sound royalty-free",
    "Lo-Fi Music Pack Vol. 3": "Ovani Sound royalty-free",
    "Gothic Fantasy Sound FX Pack Vol. 1": "Ovani Sound royalty-free",
    "Inventory Sound FX Pack Vol. 2": "Ovani Sound royalty-free",
    "Medieval Fantasy Sound FX Pack Vol. 4": "Ovani Sound royalty-free",
    "Footsteps Sound FX Asset Pack": "ElvGames (credit required)",
    "Game Sounds FX Pack I": "ElvGames (credit required)",
    "Game Sounds FX Pack II": "ElvGames (credit required)",
    "Sci-Fi UI Sounds FX Asset Pack": "ElvGames (credit required)",
    "Game SFX Treasury v1.1": "NO LICENSE FILE FOUND - confirm before release",
}
AUDIO = (".wav", ".ogg", ".mp3")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pack_of(parts):
    for part in parts:
        for name in LICENSES:
            if part.startswith(name):
                return name
    return parts[0] if parts else "?"


def index_sources():
    index = {}
    for path in GAMEDEV.rglob("*"):
        if "__MACOSX" in path.parts or not path.is_file():
            continue
        rel = path.relative_to(GAMEDEV)
        if path.suffix.lower() in AUDIO:
            index.setdefault(digest(path.read_bytes()), (pack_of(rel.parts), str(rel)))
        elif path.suffix.lower() == ".zip":
            try:
                with zipfile.ZipFile(path) as zf:
                    for name in zf.namelist():
                        if "__MACOSX" in name or not name.lower().endswith(AUDIO):
                            continue
                        pack = pack_of([Path(name).parts[0], path.stem])
                        index.setdefault(digest(zf.read(name)), (pack, f"{rel}!{name}"))
            except zipfile.BadZipFile:
                pass
    return index


def main():
    index = index_sources()
    rows = []
    for folder in ("Music", "Sounds"):
        for path in sorted((ROOT / folder).rglob("*")):
            if path.is_file() and path.suffix.lower() in AUDIO:
                pack, source = index.get(digest(path.read_bytes()), ("unknown", ""))
                rows.append((path.relative_to(ROOT).as_posix(), pack, LICENSES.get(pack, ""), source))
    lines = ["# Audio provenance", "",
             "Generated by `tools/audio/audio_provenance.py`: every audio file under Music/ and Sounds/",
             "matched to a pack in Desktop\\GameDev by exact content hash. \"unknown\" means no byte-identical",
             "file was found (it may be edited/converted, or from a pack not on this machine); it is not a",
             "license determination. Music loops made by `make_music_loops.py` are derived (tail-folded,",
             "OGG-encoded) and listed in `Music/music_manifest.json` instead.", "",
             "| File | Pack | License | Source |", "|---|---|---|---|"]
    lines += [f"| `{f}` | {p} | {l} | {s} |" for f, p, l, s in rows]
    out = ROOT / "docs" / "AUDIO_PROVENANCE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    counts = {}
    for _, p, _, _ in rows:
        counts[p] = counts.get(p, 0) + 1
    for p, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"{n:4d}  {p}")


if __name__ == "__main__":
    main()
